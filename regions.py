def _rx(stems):
    return re.compile("(" + "|".join(re.escape(s) for s in stems) + ")")


_RX = {DONETSK: _rx(_DONETSK_STEMS), LUHANSK: _rx(_LUHANSK_STEMS)}

# «родом з…», «народився у…», «мешкала в…», «з Краматорська», «із Сєвєродонецька»
_ORIGIN_RX = re.compile(
    r"(родом|уродж|народи|мешка|прожива|жив |жила |жили |виріс|виросла|"
    r"(?<![\w-])(з|із|зі)\s+[А-ЯІЇЄҐ])"
)


def normalize(text: str) -> str:
    """Уніфікує апострофи й пробіли."""
    if not text:
        return ""
    text = text.replace("ʼ", "'").replace("’", "'").replace("`", "'")
    text = text.replace("\xa0", " ")
    return re.sub(r"\s+", " ", text).strip()


def find_regions(text: str) -> set:
    """Усі регіони, згадані в тексті."""
    text = normalize(text)
    return {reg for reg, rx in _RX.items() if rx.search(text)}


def origin_regions(text: str) -> set:
    """Регіони, згадані саме як походження/проживання людини
    («родом з Краматорська», «мешкала на Донеччині»),
    а не як місце бою («загинув під Бахмутом»)."""
    found = set()
    for sentence in re.split(r"(?<=[.!?])\s+", normalize(text)):
        if not _ORIGIN_RX.search(sentence):
            continue
        # не рахуємо речення про загибель чи бої
        if re.search(r"загин|бо[їя]|оборон|штурм|позиці|напрямк", sentence, re.I):
            continue
        found |= find_regions(sentence)
    return found


def region_from_field(value: str):
    """'м. Слов'янськ, Донецька область' -> DONETSK"""
    value = normalize(value)
    for reg, name in OBLAST_FIELD.items():
        if name in value:
            return reg
    return None


